export function translate(locale: Locale, key: string): string {
  return STRINGS[locale]?.[key] ?? STRINGS.en[key] ?? key;
}

export type Translator = (key: string) => string;

/** Chinese translator for the service helpers whose callers do not pass one (tests, non-React code). */
export const zhT: Translator = (key) => translate("zh", key);

/** Fill `{name}` placeholders: `fill(t("x"), { n: 3 })`. A placeholder with no value stays as written. */
export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}
